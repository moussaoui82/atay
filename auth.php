                }

                if (input.val().length > 1) {
                    inputParent.show();
                    inputParent.find('input, select').prop('disabled', false);
                } else {
                    inputParent.hide();
                    inputParent.find('input, select').prop('disabled', true);
                }
            }

            updateFormState();

            selectElement.on('change', updateFormState);
            input.on('input', updateFormState);
        });
